def setup_request_logging(app):
    @app.before_request
    def before_request():
        # not logging /static call
        if not request.path.startswith("/static"):
            g.start_time = time.time()
            g.request_id = generate_request_id()

    @app.after_request
    def after_request(res):
        # not logging /static call
        if (
            not request.path.startswith("/static")
            and not request.path.startswith("/git")
            and not request.path.startswith("/favicon.ico")
            and not request.path.startswith("/health")
        ):
            start_time = g.start_time or time.time()
            LOG.d(
                "%s %s %s %s %s, takes %s",
                request.remote_addr,
                request.method,
                request.path,
                request.args,
                res.status_code,
                time.time() - start_time,
            )
        return res


def get_current_user():
    try:
        return g.user
    except AttributeError:
        return current_user


def setup_error_page(app):
    def _error(message: str, code: int):
        return jsonify(error=message), code

    @app.errorhandler(400)
    def bad_request(e):
        return _error("Bad Request", 400)

    @app.errorhandler(401)
    def unauthorized(e):
        return _error("Unauthorized", 401)

    @app.errorhandler(403)
    def forbidden(e):
        return _error("Forbidden", 403)

    @app.errorhandler(429)
    def rate_limited(e):
        LOG.w(
            "Client hit rate limit on path %s, user:%s",
            request.path,
            get_current_user(),
        )
        return _error("Rate limit exceeded", 429)

    @app.errorhandler(404)
    def page_not_found(e):
        if request.path.startswith("/api/"):
            return _error("No such endpoint", 404)
        return _error("Not found", 404)

    @app.errorhandler(405)
    def wrong_method(e):
        return _error("Method not allowed", 405)

    @app.errorhandler(Exception)
    def error_handler(e):
        LOG.e(e)
        return _error("Internal error", 500)


